// Regenerates FRENCH_REVIEW.md from the shipped Defs + French DefInjected XML.
// Per TRANSLATIONS.md section 3: read-only, never hand-edit the table.
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DEFS_DIR = path.join(ROOT, 'Mod', 'Defs');
const FR_DIR = path.join(ROOT, 'Mod', 'Languages', 'French', 'DefInjected');
const OUT = path.join(ROOT, 'FRENCH_REVIEW.md');

// [englishDefsFile, frenchDefInjectedFile, defTag, fields]
const PAIRS = [
  ['ThingDefs_Misc/Masks.xml', 'ThingDef/Masks.xml', 'ThingDef', ['label', 'description']],
  ['ThingDefs_Misc/Decorations.xml', 'ThingDef/Decorations.xml', 'ThingDef', ['label', 'description']],
  ['ThingDefs_Misc/Candy.xml', 'ThingDef/Candy.xml', 'ThingDef', ['label', 'description']],
  ['RecipeDefs/Recipes_Candy.xml', 'RecipeDef/Recipes_Candy.xml', 'RecipeDef', ['label', 'description', 'jobString']],
];

function extractEnglish(xml, defTag, fields) {
  const entries = [];
  const blockRe = new RegExp(`<${defTag}\\b[^>]*>([\\s\\S]*?)<\\/${defTag}>`, 'g');
  let m;
  while ((m = blockRe.exec(xml))) {
    const block = m[1];
    const defNameM = block.match(/<defName>([^<]*)<\/defName>/);
    if (!defNameM) continue; // Abstract base, no defName
    const defName = defNameM[1];
    const row = { defName };
    for (const field of fields) {
      const fieldRe = new RegExp(`<${field}>([\\s\\S]*?)<\\/${field}>`);
      const fm = block.match(fieldRe);
      row[field] = fm ? fm[1].trim() : null;
    }
    entries.push(row);
  }
  return entries;
}

function extractFrench(xml) {
  const map = {};
  const re = /<([A-Za-z0-9_]+\.[A-Za-z0-9_]+)>([\s\S]*?)<\/\1>/g;
  let m;
  while ((m = re.exec(xml))) map[m[1]] = m[2].trim();
  return map;
}

function esc(cell) {
  if (cell == null) return '';
  return cell.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

let out = '# French review — Halloween Monster Mash Renew\n\n';
out += 'Generated by `scripts/Generate-FrenchReview.cjs` from the shipped Defs + French DefInjected XML. Never hand-edit.\n\n';
out += 'Original: this mod has no source in another language. Killer_Diller wrote the original `[KD] Halloween Monster Mash` in English; the "Original" column below repeats the English column.\n\n';

for (const [enRel, frRel, defTag, fields] of PAIRS) {
  const enPath = path.join(DEFS_DIR, enRel);
  const frPath = path.join(FR_DIR, frRel);
  const enXml = fs.readFileSync(enPath, 'utf8');
  const frXml = fs.readFileSync(frPath, 'utf8');
  const enEntries = extractEnglish(enXml, defTag, fields);
  const frMap = extractFrench(frXml);

  out += `## ${enRel.replace(/\\/g, '/')}\n\n`;
  out += `French source: \`Mod/Languages/French/DefInjected/${frRel.replace(/\\/g, '/')}\`\n\n`;
  out += '| Key or path | Original | English | French |\n|---|---|---|---|\n';

  for (const row of enEntries) {
    for (const field of fields) {
      if (row[field] == null) continue;
      const key = `${row.defName}.${field}`;
      const en = row[field];
      const fr = frMap[key];
      if (fr === undefined) continue; // no French entry: not this mod's coverage gap to fabricate
      out += `| ${esc(key)} | ${esc(en)} | ${esc(en)} | ${esc(fr)} |\n`;
    }
  }
  out += '\n';
}

fs.writeFileSync(OUT, out, 'utf8');
console.log('Wrote', OUT);
